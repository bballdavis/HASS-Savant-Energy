"""Generate reviewable docs from source without importing Home Assistant code."""
import argparse
import ast
import json
from pathlib import Path
import sys

import yaml


class ExtractionError(ValueError):
    pass


def cell(value):
    text = json.dumps(value, ensure_ascii=False) if not isinstance(value, str) else value
    return text.replace('|', '\\|').replace('\n', ' ').replace('<', '&lt;').replace('>', '&gt;')


def table(headers, rows):
    return '\n'.join(['| ' + ' | '.join(headers) + ' |', '| ' + ' | '.join(['---'] * len(headers)) + ' |'] +
                     ['| ' + ' | '.join(cell(v) for v in row) + ' |' for row in rows]) + '\n'


def page(title, sources, body):
    return ('---\ntitle: ' + title + '\n---\n\n'
            '<!-- Generated by website/scripts/generate_reference.py. Do not edit. -->\n\n'
            'Generated from ' + ', '.join('`' + s + '`' for s in sources) + '. '
            'Edit the source, then run `npm run docs:generate` in `website/`.\n\n' + body)


def parse_constants(root):
    tree = ast.parse((root / 'custom_components/savant_energy/const.py').read_text())
    values = {}
    for node in tree.body:
        if isinstance(node, ast.Assign) and len(node.targets) == 1 and isinstance(node.targets[0], ast.Name):
            try:
                values[node.targets[0].id] = literal(node.value, values)
            except ExtractionError:
                # Unrelated dynamic constants are allowed; a requested value must resolve below.
                pass
    return values


def literal(node, constants):
    if isinstance(node, ast.Name) and node.id in constants:
        return constants[node.id]
    try:
        return ast.literal_eval(node)
    except (ValueError, TypeError):
        raise ExtractionError('Unsupported static value: ' + ast.dump(node))


def schema_fields(schema, constants):
    if not (isinstance(schema, ast.Call) and isinstance(schema.func, ast.Attribute) and
            isinstance(schema.func.value, ast.Name) and schema.func.value.id == 'vol' and
            schema.func.attr == 'Schema' and len(schema.args) == 1 and isinstance(schema.args[0], ast.Dict)):
        raise ExtractionError('Expected a literal vol.Schema dictionary')
    return dict_fields(schema.args[0], constants)


def dict_fields(dictionary, constants):
    fields = []
    for key, value in zip(dictionary.keys, dictionary.values):
        if not (isinstance(key, ast.Call) and isinstance(key.func, ast.Attribute) and
                isinstance(key.func.value, ast.Name) and key.func.value.id == 'vol' and
                key.func.attr in ('Required', 'Optional') and len(key.args) == 1):
            raise ExtractionError('Unsupported schema field')
        fields.append((literal(key.args[0], constants), key.func.attr == 'Required', key, value))
    return fields


def option_fields(method, schema, constants):
    """Accept literal forms or the reviewed Current/Legacy field composition."""
    if isinstance(schema, ast.Call) and len(schema.args) == 1 and isinstance(schema.args[0], ast.Dict):
        return [(*field, 'All') for field in schema_fields(schema, constants)]
    if not (isinstance(schema, ast.Call) and isinstance(schema.func, ast.Attribute) and
            isinstance(schema.func.value, ast.Name) and schema.func.value.id == 'vol' and
            schema.func.attr == 'Schema' and len(schema.args) == 1 and
            isinstance(schema.args[0], ast.Name) and schema.args[0].id == 'fields'):
        raise ExtractionError('Unsupported composed options schema')
    declarations = [n for n in method.body if isinstance(n, ast.Assign) and
                    len(n.targets) == 1 and isinstance(n.targets[0], ast.Name) and n.targets[0].id == 'fields']
    expected_mode = ast.parse('self.config_entry.data.get(CONF_MODE, DEFAULT_MODE) == MODE_CURRENT', mode='eval').body
    modes = [n.value for n in method.body if isinstance(n, ast.Assign) and
             len(n.targets) == 1 and isinstance(n.targets[0], ast.Name) and n.targets[0].id == 'current_mode']
    if len(modes) != 1 or ast.dump(modes[0]) != ast.dump(expected_mode):
        raise ExtractionError('Unsupported options mode selection')
    if len(declarations) != 1 or not isinstance(declarations[0].value, ast.Dict):
        raise ExtractionError('Expected one literal options fields declaration')
    tail = method.body[method.body.index(declarations[0]) + 1:]
    if not (len(tail) == 2 and isinstance(tail[0], ast.If) and
            isinstance(tail[0].test, ast.Name) and tail[0].test.id == 'current_mode' and
            isinstance(tail[1], ast.Return)):
        raise ExtractionError('Unsupported options field composition')
    rows = [(*field, 'All') for field in dict_fields(declarations[0].value, constants)]
    allowed_fields_names = {id(declarations[0].targets[0]), id(schema.args[0])}
    for statements, mode in ((tail[0].body, 'Current'), (tail[0].orelse, 'Legacy')):
        if len(statements) != 1 or not isinstance(statements[0], ast.Assign) or len(statements[0].targets) != 1:
            raise ExtractionError('Unsupported mode-specific options fields')
        assignment = statements[0]
        target = assignment.targets[0]
        if not (isinstance(target, ast.Subscript) and isinstance(target.value, ast.Name) and target.value.id == 'fields'):
            raise ExtractionError('Expected a mode-specific field assignment')
        allowed_fields_names.add(id(target.value))
        rows.extend((*field, mode) for field in dict_fields(ast.Dict(keys=[target.slice], values=[assignment.value]), constants))
    if any(isinstance(n, ast.Name) and n.id == 'fields' and id(n) not in allowed_fields_names for n in ast.walk(method)):
        raise ExtractionError('Unsupported options fields access or mutation')
    if len({row[0] for row in rows}) != len(rows):
        raise ExtractionError('Duplicate options fields')
    return rows


def extract_options(tree, constants, labels):
    classes = [n for n in tree.body if isinstance(n, ast.ClassDef) and n.name == 'OptionsFlowHandler']
    if len(classes) != 1:
        raise ExtractionError('OptionsFlowHandler not found uniquely')
    methods = [n for n in classes[0].body if isinstance(n, ast.AsyncFunctionDef) and n.name == 'async_step_init']
    if len(methods) != 1:
        raise ExtractionError('Options form not found uniquely')
    forms = [n for n in ast.walk(methods[0]) if isinstance(n, ast.Call) and isinstance(n.func, ast.Attribute) and n.func.attr == 'async_show_form']
    if len(forms) != 1:
        raise ExtractionError('Expected one options form')
    schemas = [k.value for k in forms[0].keywords if k.arg == 'data_schema']
    if len(schemas) != 1:
        raise ExtractionError('Options schema missing')
    rows = []
    for name, required, key, validator, mode in option_fields(methods[0], schemas[0], constants):
        if name not in labels:
            raise ExtractionError('Missing option label: ' + name)
        defaults = [k.value for k in key.keywords if k.arg == 'default']
        if len(defaults) != 1:
            raise ExtractionError('Missing default: ' + name)
        default_node = defaults[0]
        if isinstance(default_node, ast.Call):
            if not (isinstance(default_node.func, ast.Name) and default_node.func.id == '_opt' and len(default_node.args) == 2):
                raise ExtractionError('Unsupported default expression: ' + name)
            default_node = default_node.args[1]
        default = literal(default_node, constants)
        if isinstance(validator, ast.Name) and validator.id in ('int', 'bool', 'str'):
            kind = {'int': 'Integer', 'bool': 'Boolean', 'str': 'Text'}[validator.id]
        elif isinstance(validator, ast.Call) and isinstance(validator.func, ast.Attribute) and isinstance(validator.func.value, ast.Name) and validator.func.value.id == 'vol':
            if validator.func.attr == 'In' and len(validator.args) == 1:
                kind = 'One of: ' + ', '.join(map(str, literal(validator.args[0], constants)))
            elif validator.func.attr == 'Coerce' and len(validator.args) == 1 and isinstance(validator.args[0], ast.Name) and validator.args[0].id == 'int':
                kind = 'Integer'
            else:
                raise ExtractionError('Unsupported option validator: ' + name)
        else:
            raise ExtractionError('Unsupported option validator: ' + name)
        rows.append(('`' + name + '`', labels[name], '`' + json.dumps(default) + '`', kind, mode))
    if {r[0].strip('`') for r in rows} != set(labels):
        raise ExtractionError('Options labels and form fields differ')
    return rows


def extract_services(tree, constants, services):
    registered = {}
    for node in ast.walk(tree):
        if not (isinstance(node, ast.Call) and isinstance(node.func, ast.Attribute) and node.func.attr == 'async_register'):
            continue
        if len(node.args) < 3:
            raise ExtractionError('Unsupported service registration')
        name = literal(node.args[1], constants)
        schema = next((k.value for k in node.keywords if k.arg == 'schema'), None)
        registered[name] = schema_fields(schema, constants) if schema else []
    if set(registered) != set(services):
        raise ExtractionError('Service definitions and registrations differ')
    sections = []
    for name, definition in services.items():
        sections += ['## `savant_energy.' + name + '`\n', definition['description'] + '\n']
        fields = definition.get('fields', {})
        if set(fields) != {f[0] for f in registered[name]}:
            raise ExtractionError('Service fields differ: ' + name)
        rows = []
        for field, required, _, validator in registered[name]:
            if bool(fields[field].get('required', False)) != required:
                raise ExtractionError('Service required flag differs: ' + name + '.' + field)
            if not isinstance(validator, ast.Name) or validator.id not in ('str', 'dict', 'list', 'bool', 'int'):
                raise ExtractionError('Unsupported service validator')
            example = fields[field].get('example')
            rows.append(('`' + field + '`', 'Yes' if required else 'No', validator.id,
                         fields[field].get('description', ''), '`' + cell(example) + '`' if example is not None else '—'))
        sections.append(table(['Field', 'Required', 'Type', 'Description', 'Example'], rows) if rows else 'No fields.\n')
    return '\n'.join(sections)


def generate(root):
    base = root / 'custom_components/savant_energy'
    constants = parse_constants(root)
    labels = json.loads((base / 'translations/en.json').read_text())
    flow = ast.parse((base / 'config_flow.py').read_text())
    services = yaml.safe_load((base / 'services.yaml').read_text())
    api = ast.parse((base / 'api.py').read_text())
    options = extract_options(flow, constants, labels['options']['step']['init']['data'])
    offered = {k.value.value for n in ast.walk(flow) if isinstance(n, ast.Call) and
               isinstance(n.func, ast.Attribute) and n.func.attr == 'async_show_form'
               for k in n.keywords if k.arg == 'step_id' and isinstance(k.value, ast.Constant)}
    setup = ['This is a label reference, not a sequence to complete. Follow [Current setup](../../connect/current.md) or [Legacy setup](../../legacy/README.md). Retained compatibility labels do not imply a screen is offered during new setup.\n']
    for section in ('config', 'options'):
        for key, step in labels[section]['step'].items():
            setup += ['## ' + cell(step['title']) + '\n',
                      '`' + section + '.' + key + '` · ' + ('Form present in source' if key in offered else 'Retained compatibility labels; no form offered') + '\n',
                      cell(step.get('description', '')) + '\n']
            if step.get('data'):
                setup.append(table(['Field', 'Label', 'Help'], [('`' + k + '`', v, step.get('data_description', {}).get(k, '—')) for k, v in step['data'].items()]))
    errors = ['Match the displayed message to the troubleshooting guide. Some messages are retained for compatibility.\n']
    for section in ('config', 'options'):
        errors += ['## ' + section.capitalize() + ' errors\n', table(['Key', 'Message'], [('`' + k + '`', v) for k, v in labels[section]['error'].items()])]
    return {
        'services.md': page('Service fields', ['services.yaml', 'api.py'],
                            'These are Home Assistant service fields. For HTTP requests, see the [REST API](../rest-api.md). Handler return dictionaries do not by themselves guarantee Home Assistant service response support. Use switch entity IDs in relay-state mappings; review the REST guide for the existing create/update behavior and defaults.\n\n' + extract_services(api, constants, services)),
        'options.md': page('Option defaults', ['config_flow.py', 'const.py', 'translations/en.json'],
                           'Defaults below apply when no saved value exists. Mode-specific fields are hidden in the other mode; saved values are retained. Host and authentication settings belong in **Reconfigure**, not runtime options. See [Options](../../usage/options.md) for guidance.\n\n' + table(['Key', 'UI label', 'Default', 'Type / choices', 'Mode'], options)),
        'setup.md': page('Setup labels', ['config_flow.py', 'translations/en.json'], '\n'.join(setup)),
        'errors.md': page('Error messages', ['translations/en.json'], '\n'.join(errors)),
    }


def run(root, check=False):
    outputs = generate(root)  # Validate every source before any writes.
    dest = root / 'docs/reference/generated'
    stale = []
    for filename, content in outputs.items():
        path = dest / filename
        if not path.exists() or path.read_text() != content:
            stale.append(filename)
            if not check:
                dest.mkdir(parents=True, exist_ok=True)
                path.write_text(content)
    if check and stale:
        raise ExtractionError('Stale generated reference: ' + ', '.join(stale) + '. Run npm run docs:generate.')
    return len(outputs)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Compare without writing files')
    args = parser.parse_args()
    try:
        count = run(Path(__file__).resolve().parents[2], args.check)
        print(('Checked' if args.check else 'Generated') + ' ' + str(count) + ' reference pages.')
    except (ExtractionError, KeyError, SyntaxError, yaml.YAMLError) as error:
        print('Reference extraction failed: ' + str(error), file=sys.stderr)
        sys.exit(1)
